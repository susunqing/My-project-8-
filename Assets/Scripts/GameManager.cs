using System.Collections;
using System.Collections.Generic;
using UnityEngine;

public class GameManager : MonoBehaviour
{

    // Start is called before the first frame update
    //单例
    // 1. 定义一个静态私有字段，用来存储真正的实例
    private static GameManager _instance;

    // 2. 将 Instance 改为带逻辑的属性
    public static GameManager Instance
    {
        get
        {
            // 如果内存中还没有实例，就去场景里找
            if (_instance == null)
            {
                // 在当前场景中查找类型为 GameManager 的物体
                _instance = FindObjectOfType<GameManager>();

                // 如果场景里连这个物体都没有，可以顺便动态创建一个（可选，但非常实用）
                //if (_instance == null)
                //{
                //    GameObject obj = new GameObject("GameManager (Autogenerated)");
                //    _instance = obj.AddComponent<GameManager>();
                //}
            }
            return _instance;
        }
        // 保持私有 set，防止外部随意篡改实例
        private set => _instance = value;
    }
    //玩家数据
    [HideInInspector]
    public int unLockLevel;
    public int selectLevel;
    public int money;
    public int gunLevel;
    public Player player;
    //系统设置
    public float volume;
    public float joystickSize;
    private void Awake()
    {
        Instance = this;
        DontDestroyOnLoad(gameObject);
    }

    /// <summary>
    /// 加载关卡
    /// </summary>
    private void LoadGame()
    {
        if (PlayerPrefs.HasKey("Money"))
        {
            money = PlayerPrefs.GetInt("Money");
        }
        else
        {
            money = 0;
        }
        if (PlayerPrefs.HasKey("Levels"))
        {
            unLockLevel = PlayerPrefs.GetInt("Levels");
        }
        else
        {
            unLockLevel = 1;
        }
        if (PlayerPrefs.HasKey("Sound"))
        {
            volume = PlayerPrefs.GetFloat("Sound");
        }
        else { volume = 0; }
        if (PlayerPrefs.HasKey("JoyStick"))
        {
            joystickSize = PlayerPrefs.GetFloat("JiyStick");

        }
        else
        {
            joystickSize = 0.3f;
        }
    }
}